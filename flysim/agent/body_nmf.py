"""Realistic body: NeuroMechFly v2 (flygym, EPFL; Wang-Chen et al. 2024, Nature Methods).

Physics (MuJoCo, 0.1 ms step): rigid-body fly with 42 actuated leg DoFs, gravity, friction,
tarsal adhesion, leg-ground and leg-apple contacts, fly-fly collisions. Walking is generated by
NeuroMechFly's hybrid CPG + sensory-feedback controller, steered by a two-channel descending
drive (left/right), which is how descending neurons control walking in that model.
Our connectome brain provides that descending drive from identified DNs (motor.py).

ASSUMPTION(A36): flight is not part of NeuroMechFly v2. During flight the fly's free joint is
driven kinematically by the flight commands (same reduced flight model as body.py); take-off
and landing hand over between kinematic flight and physics.
"""
import itertools

import mujoco
import numpy as np
from flygym import Simulation
from flygym.anatomy import BodySegment, ContactBodiesPreset
from flygym.compose import ContactParams, FlatGroundWorld
from flygym.utils.math import Rotation3D
from flygym.utils.mjcf import GEOM_TYPES
from flygym_demo.complex_terrain import (HybridControllerObservation, HybridTurningController,
                                         LocomotionAction, PreprogrammedSteps,
                                         apply_locomotion_action, make_locomotion_fly)

LEGS = ["lf", "lm", "lh", "rf", "rm", "rh"]
LEG_NERVE = {"f": "ProLN", "m": "MesoLN", "h": "MetaLN"}


class NMFArena:
    """One MuJoCo world shared by all flies: floor + apple sphere."""

    def __init__(self, apples, _unused, names_poses, half_size: float = 1000.0, arena: float = None,
                 seeds: dict = None):
        """apples: list of (center xyz, radius) in mm."""
        if not isinstance(apples, list):            # backward compatible (center, r) call
            apples = [(apples, _unused)]
        self.world = FlatGroundWorld(half_size=half_size)
        self.apple_geoms = []
        for k, (c, r) in enumerate(apples):
            g = self.world.mjcf_root.worldbody.add_geom(
                type=GEOM_TYPES["sphere"], name=f"apple{k}", pos=tuple(c), size=(r, 0, 0),
                rgba=(0.6, 0.45, 0.15, 1), contype=0, conaffinity=0)
            # legs collide with every 'ground' geom -> they can stand and walk on each apple
            self.world.ground_geoms.append(g)
            self.apple_geoms.append(g)
        # container walls: thin vertical boxes; flies can stand and walk on them like on the floor
        self.wall_ids_names = []
        if arena is not None:
            h = max(30.0, arena)
            for k, (px, py, sx, sy) in enumerate(((arena + 1, 0, 1, arena + 2), (-arena - 1, 0, 1, arena + 2),
                                                  (0, arena + 1, arena + 2, 1), (0, -arena - 1, arena + 2, 1))):
                g = self.world.mjcf_root.worldbody.add_geom(
                    type=GEOM_TYPES["box"], name=f"wall{k}", pos=(px, py, h / 2), size=(sx, sy, h / 2),
                    rgba=(0.8, 0.8, 0.8, 0.15), contype=0, conaffinity=0)
                self.world.ground_geoms.append(g)
                self.wall_ids_names.append(f"wall{k}")
        self.flies = {}
        for item in names_poses:
            name, pos, yaw = item[:3]
            R = item[3] if len(item) > 3 else None
            q = Rotation3D("quat", [np.cos(yaw / 2), 0.0, 0.0, np.sin(yaw / 2)])
            spawn = [pos[0], pos[1], 0.8]
            if R is not None and pos[2] > 1.5:
                # standing on an apple or a wall: respawn in the same place and orientation
                from scipy.spatial.transform import Rotation as _Rot
                x, y, z, w = _Rot.from_matrix(np.asarray(R, float)).as_quat()
                q = Rotation3D("quat", [w, x, y, z])
                spawn = list(np.asarray(pos, float) + 0.5 * np.asarray(R, float)[:, 2])
            fly = make_locomotion_fly(name=name, add_adhesion=True, colorize=False)
            self.world.add_fly(fly, spawn, q,
                               bodysegs_with_ground_contact=ContactBodiesPreset.TIBIA_TARSUS_ONLY,
                               add_ground_contact_sensors=False)
            self.flies[name] = fly
        self._fly_fly_pairs()
        self.sim = Simulation(self.world)
        self.pps = PreprogrammedSteps()
        self.ctrl = {}
        self.sim.reset()
        for k, (name, fly) in enumerate(self.flies.items()):
            order = fly.get_actuated_jointdofs_order("position")
            c = HybridTurningController(timestep=self.sim.timestep, preprogrammed_steps=self.pps,
                                        output_dof_order=order)
            c.reset(seed=int((seeds or {}).get(name, k)))   # per-fly seed, independent replicates
            self.ctrl[name] = c
            apply_locomotion_action(self.sim, name, LocomotionAction(
                joint_angles=self.pps.default_pose_by_dof_order(order),
                adhesion_onoff=np.ones(6, bool)))
        self.sim.warmup()
        m, d = self.sim.mj_model, self.sim.mj_data
        self.apple_ids = {mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_GEOM, f"apple{k}")
                          for k in range(len(self.apple_geoms))}
        self.wall_ids = {mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_GEOM, n) for n in self.wall_ids_names}
        self.floor_id = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_GEOM, "ground_plane")
        self.drive = {n: np.zeros(2) for n in self.flies}
        self.kinematic = {}   # name -> (pos, yaw) while flying
        self.chains = {}      # name -> MotorChain (motor-neuron -> muscle -> joint offsets)
        self.lesions = {}     # name -> BodySchema (paralyzed / amputated legs)
        self.dof_index = {n: {f"{n}/{d.name}": i for i, d in
                              enumerate(f.get_actuated_jointdofs_order("position"))}
                          for n, f in self.flies.items()}
        self._index()

    def _fly_fly_pairs(self):
        names = list(self.flies)
        cp = ContactParams()
        for a, b in itertools.combinations(names, 2):
            fa, fb = self.flies[a], self.flies[b]
            segs = [s for s in fa.bodyseg_to_mjcfgeom
                    if s.link in ("thorax", "head", "abdomen12", "abdomen3", "abdomen4", "abdomen5")]
            for sa, sb in itertools.product(segs, segs):
                for ga in fa.bodyseg_to_mjcfgeom[sa]:
                    for gb in fb.bodyseg_to_mjcfgeom[BodySegment(sb.name)]:
                        self.world.mjcf_root.add_pair(geomname1=ga.name, geomname2=gb.name,
                                                      name=f"{ga.name}-{gb.name}",
                                                      friction=cp.get_friction_tuple(),
                                                      solref=cp.get_solref_tuple(),
                                                      solimp=cp.get_solimp_tuple())

    def _index(self):
        m = self.sim.mj_model
        self.thorax = {}
        self.head = {}
        self.leg_geoms = {}
        self.free_adr = {}
        for name, fly in self.flies.items():
            order = fly.get_bodysegs_order()
            ids = self.sim._internal_bodyids_by_fly[name]
            self.thorax[name] = ids[order.index(BodySegment("c_thorax"))]
            self.head[name] = ids[order.index(BodySegment("c_head"))]
            geoms = {}
            for seg, gl in fly.bodyseg_to_mjcfgeom.items():
                if seg.link in ("tibia", "tarsus1", "tarsus2", "tarsus3", "tarsus4", "tarsus5"):
                    leg = seg.name[:2]
                    for g in gl:
                        gid = mujoco.mj_name2id(m, mujoco.mjtObj.mjOBJ_GEOM, g.name)
                        if gid >= 0:
                            geoms[gid] = leg
            self.leg_geoms[name] = geoms
            # free joint of this fly = the joint of its root body
            root = ids[0]
            while m.body_parentid[root] != 0:
                root = m.body_parentid[root]
            jid = m.body_jntadr[root]
            self.free_adr[name] = (m.jnt_qposadr[jid], m.jnt_dofadr[jid])

    def tucked_pose(self, name):
        """Flight posture: legs drawn up under the body (tibiae flexed, femora raised)."""
        if not hasattr(self, "_tucked"):
            self._tucked = {}
        if name not in self._tucked:
            order = self.flies[name].get_actuated_jointdofs_order("position")
            ja = np.array(self.pps.default_pose_by_dof_order(order), dtype=float)
            for d, i in self.dof_index[name].items():
                if "tibia-pitch" in d:
                    ja[i] = 2.3 if ja[i] > 0 else -2.3
                elif "trochanterfemur-pitch" in d:
                    ja[i] = ja[i] - 0.8 if ja[i] < 0 else ja[i] + 0.8
            self._tucked[name] = ja
        return self._tucked[name]

    def _apply_leg_lesions(self, name, act, sch):
        ja = np.array(act.joint_angles, dtype=float)
        adh = np.array(act.adhesion_onoff, dtype=bool)
        rest = self.pps.default_pose_by_dof_order(self.flies[name].get_actuated_jointdofs_order("position"))
        for k, leg in enumerate(LEGS):
            st = sch.legs[leg]
            if st == "intact":
                continue
            idx = [i for d, i in self.dof_index[name].items() if f"/{leg}_" in d or f"-{leg}_" in d]
            if st == "paralyzed":
                ja[idx] = rest[idx]
            else:  # amputated: fold the leg up against the body, away from the substrate
                for d, i in self.dof_index[name].items():
                    if (f"/{leg}_" in d or f"-{leg}_" in d):
                        if "tibia-pitch" in d:
                            ja[i] = 2.5 if rest[i] > 0 else -2.5
                        elif "trochanterfemur-pitch" in d:
                            ja[i] = rest[i] - 1.0 if rest[i] < 0 else rest[i] + 1.0
            adh[k] = False
        return LocomotionAction(joint_angles=ja, adhesion_onoff=adh)

    # ---------------------------------------------------------------------------------------
    def pose(self, name):
        d = self.sim.mj_data
        p = d.xpos[self.thorax[name]].copy()
        R = d.xmat[self.thorax[name]].reshape(3, 3)
        return p, float(np.arctan2(R[1, 0], R[0, 0])), R

    def head_pos(self, name):
        return self.sim.mj_data.xpos[self.head[name]].copy()

    def leg_contacts(self, name):
        """{leg: 'floor'|'apple'|None} from the physics contact list."""
        d = self.sim.mj_data
        out = {leg: None for leg in LEGS}
        lg = self.leg_geoms[name]
        for i in range(d.ncon):
            c = d.contact[i]
            for g, other in ((c.geom1, c.geom2), (c.geom2, c.geom1)):
                if g in lg:
                    if other in self.apple_ids:
                        out[lg[g]] = "apple"
                    elif other in self.wall_ids and out[lg[g]] is None:
                        out[lg[g]] = "wall"
                    elif other == self.floor_id and out[lg[g]] is None:
                        out[lg[g]] = "floor"
        return out

    def set_kinematic(self, name, pos, yaw):
        qa, va = self.free_adr[name]
        d = self.sim.mj_data
        d.qpos[qa:qa + 3] = pos
        d.qpos[qa + 3:qa + 7] = [np.cos(yaw / 2), 0, 0, np.sin(yaw / 2)]
        d.qvel[va:va + 6] = 0.0

    def advance(self, dt):
        n = int(round(dt / self.sim.timestep))
        for _ in range(n):
            for name in self.flies:
                if name in self.kinematic:
                    # in the air: legs at rest pose, tarsal adhesion off (otherwise adhesion
                    # actuators pull the legs while the body is moved -> numerical blow-up)
                    order = self.flies[name].get_actuated_jointdofs_order("position")
                    apply_locomotion_action(self.sim, name, LocomotionAction(
                        joint_angles=self.pps.default_pose_by_dof_order(order),
                        adhesion_onoff=np.zeros(6, bool)))
                    self.set_kinematic(name, *self.kinematic[name])
                    qa, va = self.free_adr[name]
                    self.sim.mj_data.qvel[va:va + 6] = 0.0
                    continue
                obs = HybridControllerObservation.from_sim(self.sim, name)
                act = self.ctrl[name].step(self.drive[name], obs)
                ch = self.chains.get(name)
                if ch is not None and ch.offsets:
                    ja = np.array(act.joint_angles, dtype=float)
                    idx = self.dof_index[name]
                    for dof, dth in ch.offsets.items():
                        i = idx.get(dof)
                        if i is not None:
                            ja[i] += dth
                    act = LocomotionAction(joint_angles=ja, adhesion_onoff=act.adhesion_onoff)
                sch = self.lesions.get(name)
                if sch is not None and any(v != "intact" for v in sch.legs.values()):
                    act = self._apply_leg_lesions(name, act, sch)
                apply_locomotion_action(self.sim, name, act)
            self.sim.step()


class NMFBody:
    """Same interface as body.Body, backed by NeuroMechFly physics."""

    def __init__(self, arena: NMFArena, name: str, rng, p=None):
        from flysim.agent.body import BodyParams
        self.arena, self.name, self.rng = arena, name, rng
        self.p = p or BodyParams()
        self.mode, self.surface = "walk", "floor"
        self.proboscis, self.wing_ext, self.lunge_t, self.flight_t = False, 0.0, 0.0, 0.0
        self.contacts = {leg: None for leg in LEGS}
        self.sync()

    def sync(self):
        if self.mode == "fly":
            pos, yaw = self.arena.kinematic[self.name]
            self.pos, self.yaw = np.array(pos, float), yaw
            self.contacts = {leg: None for leg in LEGS}
            return
        self.pos, self.yaw, self.R = self.arena.pose(self.name)
        self.contacts = self.arena.leg_contacts(self.name)
        on = [c for c in self.contacts.values() if c]
        if on:
            self.surface = ("apple" if on.count("apple") >= max(1, len(on) // 2) else
                            "wall" if on.count("wall") >= max(1, len(on) // 2) else "floor")

    def heading(self):
        return np.array([np.cos(self.yaw), np.sin(self.yaw), 0.0])

    def teleport(self, pos, yaw):
        """Experimenter moves the fly (e.g. into the T-maze start): place it standing."""
        self.arena.kinematic.pop(self.name, None)
        self.mode = "walk"
        self.arena.set_kinematic(self.name, np.array([pos[0], pos[1], max(pos[2], 0.0) + 0.8]), yaw)
        self.arena.drive[self.name] = np.zeros(2)
        self.arena.advance(0.02)
        self.sync()

    def normal(self, apple_c):
        if self.mode == "fly":
            return np.array([0.0, 0.0, 1.0])
        return self.R[:, 2].copy()

    def eye(self, apple_c):
        return self.arena.head_pos(self.name) if self.mode != "fly" else self.pos + np.array([0, 0, 0.3])

    def step(self, cmd, dt, apple_c, apple_r, arena, spontaneous=True, o2_pct=20.9, vigor_factor=1.0):
        """Translate DN commands into NeuroMechFly descending drive (applied during advance)."""
        p = self.p
        # A70 hypoxia ramp x cold/poison (A93, A72) - separately, not folded into the O2 value
        vigor = float(np.clip((o2_pct - 2.0) / 6.0, 0.0, 1.0)) * float(np.clip(vigor_factor, 0.0, 1.0))
        self.proboscis = cmd["proboscis"] and self.mode == "walk" and vigor > 0
        self.wing_ext = cmd.get("song", 0.0) if self.mode == "walk" and vigor > 0 else 0.0
        if self.mode == "walk":
            if cmd["takeoff"] and vigor > 0:
                self.mode, self.flight_t = "fly", 0.0
                self.yaw_rate = 0.0       # a new flight starts without the last flight's rotation
                self.arena.kinematic[self.name] = (self.pos + 3.0 * self.normal(apple_c), self.yaw)
                self._n0 = self.normal(apple_c)
                return
            base = cmd["forward"] - cmd["backward"]
            if spontaneous:
                base += 0.35  # A30: weak intrinsic locomotor drive
            # A30: spontaneous turning is temporally correlated (turn bouts last ~0.5-1 s; Katsov &
            # Clandinin 2008; Berman et al. 2014): Ornstein-Uhlenbeck, tau 0.7 s, sd 0.4.
            # (White noise at the 10 ms brain step averaged out and gave straight-line walks.)
            a = np.exp(-dt / 0.7)
            self.turn_ou = a * getattr(self, "turn_ou", 0.0) + np.sqrt(1 - a * a) * 0.4 * self.rng.standard_normal()
            turn = cmd["turn"] + (self.turn_ou if spontaneous else 0.0)
            if self.proboscis or vigor <= 0:
                base, turn = 0.0, 0.0
            # positive turn = left: right legs stronger
            dl = np.clip(vigor * (base - 0.6 * turn), -1.0, 1.2)
            dr = np.clip(vigor * (base + 0.6 * turn), -1.0, 1.2)
            self.arena.drive[self.name] = np.array([dl, dr])
            return
        # flight: quasi-steady aerodynamics + gravity + drag (physics.py, A37). The fly body is
        # moved as a point mass; legs are not simulated in the air (A36).
        self.flight_t += dt
        pos, yaw = self.arena.kinematic[self.name]
        pos = np.array(pos, float)
        if not hasattr(self, "aero"):
            from flysim.agent.physics import FlightDynamics
            self.aero = FlightDynamics()
        if self.flight_t < p.takeoff_s:   # jump: middle legs push off (~1 m/s; Card & Dickinson 2008)
            if self.flight_t <= dt:
                self.aero.v = 600.0 * self._n0 + 200.0 * self.heading()
            amp = 0.75
        else:
            # ASSUMPTION(A36b): haltere/visual stabilisation reflexes (VNC, not in the model) hold
            # altitude ~15 mm above the apple top; DNg02 (brain) adds stroke amplitude
            target = 2 * apple_r + p.fly_clear
            reflex = 0.65 + 0.004 * (target - pos[2]) - 0.0008 * self.aero.v[2]
            amp = float(np.clip(reflex + 0.25 * cmd["flight_power"], 0.0, 1.0))
            if cmd["land"] or self.flight_t > p.max_flight_s:
                amp = 0.6   # landing: reduced stroke amplitude -> controlled descent
            if vigor <= 0:
                amp = 0.0   # stupor: free fall
            yaw += 3 * p.w_turn * cmd["turn"] * dt
            if spontaneous:
                yaw += p.spont_turn_sd * self.rng.standard_normal() * np.sqrt(dt)
        # rotational (yaw) dynamics: inertia + aerodynamic damping (~80 ms; Hesselberg & Lehmann
        # 2007), gust torques; steering from wing stroke-amplitude asymmetry (A86)
        if not hasattr(self, "yaw_rate"):
            self.yaw_rate = 0.0
        ch = self.arena.chains.get(self.name)
        sch = self.arena.lesions.get(self.name)
        dl = dr = 0.0
        if sch is not None:
            dl, dr = sch.wing_damage["left"], sch.wing_damage["right"]
            amp *= float(np.sqrt(max(0.0, 1.0 - 0.5 * (dl + dr))))
        if self.flight_t >= p.takeoff_s:
            if ch is not None and ch.has_flight_chain:
                aL = (1 - dl) * (1 + 0.3 * ch.amp_lr[0])
                aR = (1 - dr) * (1 + 0.3 * ch.amp_lr[1])
                torque = 600.0 * (aR - aL)          # larger right stroke -> turn left (+yaw)
                amp *= 1.0 + 0.2 * (ch.power_act - 0.5)
            else:  # no VNC: brain DN turning + damaged-wing asymmetry only (A36b)
                torque = 600.0 * ((1 - dr) - (1 - dl)) * 0.3
            gust = self.rng.standard_normal() * 40.0 / np.sqrt(dt / 0.01)
            self.yaw_rate += (torque + gust - self.yaw_rate / 0.08) * dt
            yaw += self.yaw_rate * dt
        wind = np.array([*getattr(self.arena, "wind", (0.0, 0.0)), 0.0]) * 1000.0
        pos = self.aero.step(pos, yaw, amp, 0.0, dt, wind=wind)
        for k in range(2):
            if abs(pos[k]) > arena - 3.0:   # wall: inelastic bounce, body kept clear of the wall
                pos[k] = np.sign(pos[k]) * (arena - 3.0)
                self.aero.v[k] *= -0.3
                yaw = np.pi - yaw if k == 0 else -yaw
        d = np.linalg.norm(pos - apple_c)
        if self.flight_t > 0.05 and (d <= apple_r + 1.0 or pos[2] <= 0.8):
            # hand back to physics with the legs clear of the surface (they touch down by gravity)
            if d <= apple_r + 1.0:
                pos = apple_c + (pos - apple_c) / d * (apple_r + 2.2)
            else:
                pos[2] = 2.2
            self.impact_speed = float(np.linalg.norm(self.aero.v))
            self.arena.set_kinematic(self.name, pos, yaw)
            del self.arena.kinematic[self.name]
            self.mode = "walk"
            self.surface = "apple" if d <= apple_r + 1.0 else "floor"
            return
        self.arena.kinematic[self.name] = (pos, yaw)
